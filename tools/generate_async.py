"""
Generates the asynchronous modules (openhab/Async*.py) from the synchronous ones.

The synchronous classes are the single source of truth. Every method keeps its
name, parameters, return values and error messages; only the I/O layer changes
(requests -> aiohttp, def -> async def, client calls -> await).

Usage:  python tools/generate_async.py
"""
import ast
import pathlib
import re

PKG = pathlib.Path(__file__).resolve().parents[1] / "openhab"
SKIP = {"__init__.py", "Client.py", "AsyncClient.py", "SSE.py"}
HEADER = "# Generated by tools/generate_async.py from {src} – do not edit by hand.\n"


def convert(source: str, filename: str) -> str:
    tree = ast.parse(source)
    classNames = [n.name for n in tree.body if isinstance(n, ast.ClassDef)]
    lines = source.split("\n")

    # 1. def -> async def for all functions except __init__
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name != "__init__":
            i = node.lineno - 1
            lines[i] = re.sub(r"^(\s*)def ", r"\1async def ", lines[i], count=1)
    out = "\n".join(lines)

    # 2. imports and type hints
    out = out.replace("from .Client import OpenHABClient, StatusResponse\n",
                      "from .AsyncClient import AsyncOpenHABClient\nfrom .Client import StatusResponse\n")
    out = re.sub(r"^import requests\n", "import asyncio\nimport aiohttp\n", out, flags=re.M)
    out = re.sub(r"\bOpenHABClient\b", "AsyncOpenHABClient", out)
    out = out.replace("AsyncAsyncOpenHABClient", "AsyncOpenHABClient")

    # 3. class names
    for name in classNames:
        out = re.sub(rf"^class {name}\b", f"class Async{name}", out, flags=re.M)

    # 4. awaits
    out = re.sub(r"(?<!await )\bself\.client\.(get|post|put|delete|executeSSE)\(", r"await self.client.\1(", out)
    out = re.sub(r"(?<!await )(?<!\.)\bclient\.executeSSE\(", r"await client.executeSSE(", out)
    out = re.sub(r"(?<!await )\b_openStream\(self", r"await _openStream(self", out)
    out = re.sub(r"return self\.(\w+)\(", r"return await self.\1(", out)

    # 5. exceptions
    out = out.replace("except requests.exceptions.HTTPError as err:", "except aiohttp.ClientResponseError as err:")
    out = out.replace("err.response.status_code", "err.status")
    out = out.replace("except requests.exceptions.RequestException as err:",
                      "except (aiohttp.ClientError, asyncio.TimeoutError) as err:")

    # 6. documentation of stream objects
    out = out.replace("requests.Response", "aiohttp.ClientResponse")
    out = out.replace("iterate with iter_lines()", "iterate with `async for line in response.content`")

    if "requests" in re.sub(r"#.*|\"\"\"[\s\S]*?\"\"\"", "", out):
        raise RuntimeError(f"{filename}: unconverted use of requests")
    return HEADER.format(src=filename) + out


def main():
    for path in sorted(PKG.glob("*.py")):
        if path.name in SKIP or path.name.startswith("Async"):
            continue
        target = PKG / f"Async{path.name}"
        result = convert(path.read_text(encoding="utf-8"), path.name)
        compile(result, str(target), "exec")
        target.write_text(result, encoding="utf-8")
        print("written", target.name)


if __name__ == "__main__":
    main()
